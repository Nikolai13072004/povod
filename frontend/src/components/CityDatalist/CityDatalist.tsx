/**
 * Подсказка городов для полей ввода (FE-022).
 *
 * Нативный `<datalist>`: браузер сам показывает выпадающий список при вводе, без
 * своей логики автодополнения. Поле остаётся свободным — можно ввести город,
 * которого нет в списке. Список общий и подключается по `list="povod-cities"`,
 * чтобы «Спб», «СПб» и «Санкт-Петербург» хотя бы визуально сходились к одному
 * написанию.
 */

/** Идентификатор для атрибута `list` у полей города. */
export const CITY_DATALIST_ID = "povod-cities";

/** Крупнейшие города — покрывают подавляющее большинство пользователей. */
const CITIES = [
  "Москва",
  "Санкт-Петербург",
  "Новосибирск",
  "Екатеринбург",
  "Казань",
  "Нижний Новгород",
  "Челябинск",
  "Самара",
  "Уфа",
  "Ростов-на-Дону",
  "Краснодар",
  "Пермь",
  "Воронеж",
  "Волгоград",
  "Красноярск",
  "Саратов",
  "Тюмень",
  "Тольятти",
  "Ижевск",
  "Барнаул",
];

export function CityDatalist() {
  return (
    <datalist id={CITY_DATALIST_ID}>
      {CITIES.map((city) => (
        <option key={city} value={city} />
      ))}
    </datalist>
  );
}
