/**
 * Куда вести человека сразу после входа.
 *
 * Вынесено из формы входа отдельной функцией: решение чисто логическое, а
 * проверять его через настоящий роутер значит тестировать react-router вместо
 * собственного правила.
 */

/** Лента по умолчанию — туда же ведут все нераспознанные случаи. */
export const DEFAULT_ROUTE = "/page-1";
export const ONBOARDING_ROUTE = "/SelectInterestPage";

/**
 * @param onboarded пройден ли онбординг
 * @param from адрес, который человек запрашивал до входа (его сохраняет `RequireAuth`)
 */
export function afterAuthRoute(onboarded: boolean, from?: string): string {
  // Онбординг важнее места назначения: без интересов лента не персонализируется,
  // а профиль остаётся пустым.
  if (!onboarded) return ONBOARDING_ROUTE;

  /*
   * Возврат на запрошенный адрес. Без него ссылка на подборку теряла смысл:
   * человек открывал её, видел экран входа, входил — и попадал в ленту без
   * фильтров, потому что адрес вместе с query-параметрами никто не сохранял.
   *
   * Принимаем только собственные пути. `//evil.example` браузер понимает как
   * адрес на чужом хосте с текущей схемой, поэтому одной проверки на ведущий
   * слэш мало.
   */
  if (!from || !from.startsWith("/") || from.startsWith("//")) return DEFAULT_ROUTE;
  // Обратный слэш некоторые браузеры трактуют как прямой — та же лазейка.
  if (from.startsWith("/\\") || from.startsWith("/%5C")) return DEFAULT_ROUTE;
  // Возвращать на сам экран входа бессмысленно: получится петля.
  if (from === "/" || from.startsWith("/?")) return DEFAULT_ROUTE;
  return from;
}
