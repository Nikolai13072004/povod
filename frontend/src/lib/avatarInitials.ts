/**
 * Инициалы для VKUI `Avatar` — но ТОЛЬКО когда фото нет.
 *
 * VKUI показывает `initials` как запасной вариант, пока/если картинка не
 * загрузилась. На медленной сети (LTE) это значит, что у человека с аватаркой
 * на пару секунд, а при неудачной загрузке — и вовсе, вместо фото видна буква.
 * Владелец просил: есть аватарка — букв быть не должно. Поэтому при заданном
 * `src` инициалы не отдаём вовсе: пустой кружок честнее буквы, которая выдаёт
 * себя за «нет фото».
 */
export function avatarInitials(
  src: string | undefined | null,
  name: string | undefined | null,
): string | undefined {
  if (src) return undefined;
  return name?.slice(0, 1) || undefined;
}
