/**
 * Единый каталог интересов и категорий событий.
 *
 * До этого список был скопирован в пяти местах — фильтр ленты, модалка выбора,
 * профиль, онбординг и форма создания, — и все пять разошлись:
 *
 *  - фильтр предлагал «Путешествия», форма создавала «Путешествие»;
 *  - «ЗОЖ» была только в профиле и форме, отфильтровать её было невозможно;
 *  - «Музей» и «Отдых» были только в фильтре — событие такой категории создать
 *    нельзя, поэтому чипы гарантированно давали пустой результат.
 *
 * Сравнение категории события с интересом — обычное сравнение строк, поэтому
 * расхождение в одну букву означает «не найдено ни одного повода».
 *
 * Форма множественного числа выбрана как каноническая: её уже используют
 * фильтр, модалка и посев на сервере (`backend/src/seed.ts`).
 */
export const INTERESTS = [
  "Спорт",
  "Искусство",
  "Путешествия",
  "IT",
  "Компьютерные игры",
  "Технологии",
  "Еда",
  "Настольные игры",
  "Наука",
  "Музыка",
  "Саморазвитие",
  "ЗОЖ",
  "Образование",
  "Кино",
  "Шопинг",
  "Ресторан",
  "Музей",
  "Отдых",
] as const;

export type Interest = (typeof INTERESTS)[number];

/**
 * Приведение метки к сравнимому виду.
 *
 * Повторяет `normalizeLabel` на сервере (`backend/src/feed.ts`): нижний регистр,
 * ё → е, обрезка пробелов. Без свёртки ё/е «Кёрлинг» и «Керлинг» — разные
 * строки, а человек считает их одним и тем же.
 */
export function normalizeInterest(value: string): string {
  return value.toLocaleLowerCase("ru").replace(/ё/g, "е").trim();
}

/** Совпадает ли хотя бы одна метка события с выбранными интересами. */
export function matchesAnyInterest(labels: readonly (string | undefined)[], selected: string[]) {
  if (selected.length === 0) return true;
  const wanted = new Set(selected.map(normalizeInterest));
  return labels.some((label) => label !== undefined && wanted.has(normalizeInterest(label)));
}
