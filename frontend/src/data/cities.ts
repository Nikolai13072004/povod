/** Регистр и «ё» не должны мешать: «ёлка»↔«елка», «Орёл»↔«орел». */
function normalizeCity(value: string): string {
  return value.toLocaleLowerCase("ru").replace(/ё/g, "е").trim();
}

/**
 * Точное совпадение с городом из справочника (регистр и «ё» неважны). Возвращает
 * КАНОНИЧЕСКОЕ написание, поэтому «москва» превращается в «Москва». `undefined` —
 * такого города нет: значит поле заполнено произвольным текстом.
 */
export function findCity(input: string): string | undefined {
  const needle = normalizeCity(input);
  if (!needle) return undefined;
  return RU_CITIES.find((city) => normalizeCity(city) === needle);
}

export function isValidCity(input: string): boolean {
  return findCity(input) !== undefined;
}

/**
 * Подсказки под ввод: сперва совпадения по началу слова, затем по вхождению.
 * Пустой ввод — самые вероятные города. Длина ограничена: выпадашка на четыре
 * строки читается сразу, на двести — уже нет.
 */
export function searchCities(input: string, limit = 6): string[] {
  const needle = normalizeCity(input);
  if (!needle) return POPULAR_CITIES.slice(0, limit);
  const starts: string[] = [];
  const contains: string[] = [];
  for (const city of RU_CITIES) {
    const normalized = normalizeCity(city);
    if (normalized.startsWith(needle)) starts.push(city);
    else if (normalized.includes(needle)) contains.push(city);
    if (starts.length >= limit) break;
  }
  return [...starts, ...contains].slice(0, limit);
}
